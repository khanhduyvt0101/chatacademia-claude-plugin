#!/usr/bin/env node
// Maintainer tool. Regenerates skills/*/SKILL.md from the ChatAcademia MCP server's own
// skill definitions so this plugin and the server's `skills/list` never drift apart.
//
//   node scripts/sync-skills.mjs --ca <chatacademia checkout>           # write skills/
//   node scripts/sync-skills.mjs --ca <chatacademia checkout> --check   # exit 1 if skills/ is stale
//
// Needs `bun` and a checkout of the (private) ChatAcademia repository with dependencies installed.
// Installers of the plugin never run this file; it is not loaded by Claude.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const caIndex = args.indexOf("--ca");
const check = args.includes("--check");
if (caIndex === -1 || !args[caIndex + 1]) {
	console.error("usage: sync-skills.mjs --ca <chatacademia checkout> [--check]");
	process.exit(2);
}
const ca = resolve(args[caIndex + 1]);
const skillsDir = join(dirname(fileURLToPath(import.meta.url)), "..", "plugins", "chatacademia", "skills");

const generator = `
const root = process.argv[1];
const lib = root + "/packages/server/lib/mcp/";
const { mcpAgentPrompts } = await import(lib + "mcp-agent-prompts");
const { mcpSkillDefinitions } = await import(lib + "mcp-skill-definitions");
const { buildMcpSkillFiles } = await import(lib + "build-mcp-skill-files");
const { researchToolContracts } = await import(lib + "research-tool-contracts");
const definitions = mcpSkillDefinitions.map(({ agentId, whenToUse }) => ({ definition: mcpAgentPrompts[agentId], whenToUse }));
console.log(JSON.stringify({ files: buildMcpSkillFiles(definitions), tools: Object.keys(researchToolContracts) }));
`;
const run = spawnSync("bun", ["-e", generator, ca], { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 });
if (run.status !== 0) {
	console.error(run.stderr || "bun failed");
	process.exit(1);
}
const { files, tools } = JSON.parse(run.stdout);

// Plugin-only rules. Everything else in each skill is the server's own text.
const preamble = `Use the ChatAcademia connector bundled with this plugin. Locate its tools by base name (the host may add a prefix). If the tools are unavailable, ask the user to connect and authorize ChatAcademia, then stop; never simulate tool results. The workflow below is complete: you do not need to fetch it again from the server.
`;
const pluginRules = `
## Plugin rules

- Only submit feedback, create checkout links or use other account tools when the user explicitly asks.
- Track evidence per source. An empty or inconclusive \`get_paper_evidence\` result supplies no new text; report it as such. An abstract returned by an earlier search may be used, labelled as search-provided, never as newly fetched or full text. A PDF URL alone does not mean the content was read. Base claims only on text actually returned, supplied or inspected.
- Copy opaque paper ids exactly from search results. Cite source URLs and label metadata, abstracts and supplied full text separately.
- When citing papers, keep bibliographic details only from verified metadata or inspected source text. Do not reconstruct journal, volume, issue, pages or DOI from memory; omit unverified fields and link the source. If sources disagree, flag the discrepancy.
- Research tools use ChatAcademia credits. Report \`creditsCharged\` from tool responses rather than estimating.
`;

const generated = new Map();
for (const [path, text] of Object.entries(files)) {
	const [name] = path.split("/");
	const marker = "\n# ";
	const at = text.indexOf(marker, text.indexOf("---", 3));
	const head = text.slice(0, at + 1).trimEnd();
	const rest = text.slice(at + 1);
	const firstBreak = rest.indexOf("\n\n");
	const title = rest.slice(0, firstBreak);
	const body = rest.slice(firstBreak + 2);
	generated.set(name, `${head}\n<!-- Generated by scripts/sync-skills.mjs from ChatAcademia's MCP skill definitions. Do not edit by hand. -->\n\n${title}\n\n${preamble}\n${body.trimEnd()}\n${pluginRules}`);
	for (const t of body.split("## Tools")[1]?.split("##")[0].matchAll(/^- ([a-z_]+)$/gm) ?? [])
		if (!tools.includes(t[1])) {
			console.error(`skill ${name} names tool ${t[1]} that the server does not expose`);
			process.exit(1);
		}
}

let stale = false;
for (const [name, text] of generated) {
	const file = join(skillsDir, name, "SKILL.md");
	const current = existsSync(file) ? readFileSync(file, "utf8") : null;
	if (current === text) continue;
	stale = true;
	if (check) console.error(`stale: plugins/chatacademia/skills/${name}/SKILL.md`);
	else {
		mkdirSync(dirname(file), { recursive: true });
		writeFileSync(file, text);
		console.log(`wrote plugins/chatacademia/skills/${name}/SKILL.md`);
	}
}
const extra = existsSync(skillsDir) ? readdirSync(skillsDir).filter((d) => !generated.has(d)) : [];
for (const d of extra) {
	stale = true;
	if (check) console.error(`stale: plugins/chatacademia/skills/${d} is no longer defined by the server`);
	else rmSync(join(skillsDir, d), { recursive: true });
}
if (check) process.exit(stale ? 1 : 0);
if (!stale) console.log("skills/ already up to date");
